/* Stall watchdog. The main loop publishes its current stage and a frame
 * counter; a separate thread on another core logs where the loop stopped
 * when no frame completes for 3, 10 and 30 seconds. Reads are racy by
 * design: they are diagnostics only and never touch GXM or the VM. */
static volatile const char* g_gxmMainStage = "boot";
static volatile uint32_t g_gxmFrameCounter = 0;
static Runner* volatile g_gxmWatchdogRunner = NULL;
extern volatile const char* g_gxmRenderStage;

static void log_memory(const char* phase, uint32_t frame, const DataWin* dw) {
    SceKernelFreeMemorySizeInfo info;
    memset(&info, 0, sizeof(info));
    info.size = sizeof(info);
    sceKernelGetFreeMemorySize(&info);
    struct mallinfo mi = mallinfo();
    unsigned blobs = 0;
    unsigned long long blobBytes = 0;
    if (dw) {
        for (uint32_t i = 0; i < dw->txtr.count; i++) {
            const Texture* t = &dw->txtr.textures[i];
            if (t->blobData && !t->mapped) { blobs++; blobBytes += t->blobSize; }
        }
    }
    char line[300];
    snprintf(line, sizeof(line),
             "NATIVE_GXM=memory phase=%s frame=%u free_user_kib=%d free_cdram_kib=%d "
             "free_phycont_kib=%d heap_arena_kib=%u heap_used_kib=%u heap_free_kib=%u "
             "txtr_blobs=%u txtr_blob_kib=%llu",
             phase, frame, info.size_user / 1024, info.size_cdram / 1024,
             info.size_phycont / 1024, (unsigned)(mi.arena / 1024),
             (unsigned)(mi.uordblks / 1024), (unsigned)(mi.fordblks / 1024),
             blobs, blobBytes / 1024ull);
    log_line(line);
}

static int gxm_watchdog_thread(SceSize args, void* argp) {
    (void)args; (void)argp;
    uint32_t last = g_gxmFrameCounter;
    uint64_t since = sceKernelGetProcessTimeWide();
    int reported = 0;
    static const uint32_t thresholdsMs[3] = {3000u, 10000u, 30000u};
    for (;;) {
        sceKernelDelayThread(500000);
        uint32_t current = g_gxmFrameCounter;
        uint64_t now = sceKernelGetProcessTimeWide();
        if (current != last) {
            if (reported) {
                char line[120];
                snprintf(line, sizeof(line),
                         "NATIVE_GXM=watchdog recovered stall_ms=%llu frame=%u",
                         (unsigned long long)((now - since) / 1000u), current);
                log_line(line);
            }
            last = current; since = now; reported = 0;
            continue;
        }
        uint64_t stalledMs = (now - since) / 1000u;
        if (reported >= 3 || stalledMs < thresholdsMs[reported]) continue;
        reported++;
        Runner* runner = g_gxmWatchdogRunner;
        const char* room = runner && runner->currentRoom ? runner->currentRoom->name : NULL;
        const char* code = runner && runner->vmContext ? runner->vmContext->currentCodeName : NULL;
        const char* stage = (const char*)g_gxmMainStage;
        const char* renderStage = (const char*)g_gxmRenderStage;
        char line[360];
        snprintf(line, sizeof(line),
                 "NATIVE_GXM=watchdog stall_ms=%llu frame=%u stage=%s render_stage=%s "
                 "room=%d room_name=%.70s code=%.90s call_depth=%d",
                 (unsigned long long)stalledMs, current, stage ? stage : "-",
                 renderStage ? renderStage : "-", runner ? runner->currentRoomIndex : -1,
                 room ? room : "-", code ? code : "-",
                 runner && runner->vmContext ? runner->vmContext->callDepth : -1);
        log_line(line);
        log_memory("watchdog", current, NULL);
    }
    return 0;
}

static void gxm_watchdog_start(void) {
    /* Higher priority than the main thread and pinned to another core, so a
     * busy main loop cannot starve it. */
    SceUID thread = sceKernelCreateThread("GXM_Watchdog", gxm_watchdog_thread,
                                          0x10000100 - 10, 16 * 1024, 0,
                                          SCE_KERNEL_CPU_MASK_USER_2, NULL);
    if (thread >= 0) sceKernelStartThread(thread, 0, NULL);
    else log_line("NATIVE_GXM=watchdog start_failed");
}

