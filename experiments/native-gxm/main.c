                perfFlush=perfPresent=0;
                runnerEventsUs=runnerAlarmsUs=runnerSpatialUs=0;
                runnerCollisionUs=runnerOtherUs=viewsUs=guiUs=0;
                perfStep=perfDraw=perfSwap=0;
