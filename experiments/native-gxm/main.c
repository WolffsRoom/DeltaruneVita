                    bs.runner->gxmStepLookupSaved=0;
                    memset(bs.runner->gxmStepDispatchUs,0,
                           sizeof(bs.runner->gxmStepDispatchUs));
                    memset(bs.runner->gxmStepPhaseUs,0,
                           sizeof(bs.runner->gxmStepPhaseUs));
                    memset(bs.runner->gxmStepPhaseCalls,0,
                           sizeof(bs.runner->gxmStepPhaseCalls));
