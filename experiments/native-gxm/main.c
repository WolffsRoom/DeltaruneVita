static void log_line(const char *line) {
    sceIoMkdir("ux0:data/deltarune", 0777);
    sceIoMkdir("ux0:data/deltarune/deltarunevita", 0777);
    SceUID fd = sceIoOpen("ux0:data/deltarune/deltarunevita/native-gxm-probe.log",
                          SCE_O_WRONLY | SCE_O_CREAT | SCE_O_APPEND, 0666);
    if (fd >= 0) {
        sceIoWrite(fd, line, strlen(line));
        sceIoWrite(fd, "\n", 1);
        sceIoClose(fd);
    }
}

/* Debug DEV capture: while DEV logging is enabled, everything appended to
 * native-gxm-probe.log is copied into devlogs/chapter N/<seq>_<room>_<time>.log
 * (the VitaGL layout), on every room change, periodically and when stopped. */
#define GXM_NATIVE_LOG "ux0:data/deltarune/deltarunevita/native-gxm-probe.log"
static char g_devCapturePath[384];
static SceOff g_devCaptureOffset = -1;

static unsigned dev_capture_next_sequence(const char* dir) {
    unsigned highest = 0;
    SceUID d = sceIoDopen(dir);
    if (d < 0) return 1;
    SceIoDirent entry;
    memset(&entry, 0, sizeof(entry));
    while (sceIoDread(d, &entry) > 0) {
        unsigned number = 0;
        size_t i = 0;
        while (entry.d_name[i] >= '0' && entry.d_name[i] <= '9') {
            number = number * 10u + (unsigned)(entry.d_name[i] - '0');
            i++;
        }
        if (i > 0 && entry.d_name[i] == '_' && number > highest) highest = number;
        memset(&entry, 0, sizeof(entry));
    }
    sceIoDclose(d);
    return highest + 1u;
}

static void dev_capture_flush(void) {
    if (g_devCaptureOffset < 0 || !g_devCapturePath[0]) return;
    SceUID in = sceIoOpen(GXM_NATIVE_LOG, SCE_O_RDONLY, 0);
    if (in < 0) return;
    SceOff end = sceIoLseek(in, 0, SCE_SEEK_END);
    if (end < g_devCaptureOffset) g_devCaptureOffset = 0; /* log was rotated */
    if (end > g_devCaptureOffset &&
        sceIoLseek(in, g_devCaptureOffset, SCE_SEEK_SET) == g_devCaptureOffset) {
        SceUID out = sceIoOpen(g_devCapturePath, SCE_O_WRONLY | SCE_O_CREAT | SCE_O_APPEND, 0666);
        if (out >= 0) {
            static char chunk[8192];
            int got;
            while ((got = sceIoRead(in, chunk, sizeof(chunk))) > 0)
                sceIoWrite(out, chunk, (SceSize)got);
            sceIoClose(out);
        }
        g_devCaptureOffset = end;
    }
    sceIoClose(in);
}

static void dev_capture_stop(void) {
    if (g_devCaptureOffset < 0) return;
    dev_capture_flush();
    SceUID out = sceIoOpen(g_devCapturePath, SCE_O_WRONLY | SCE_O_CREAT | SCE_O_APPEND, 0666);
    if (out >= 0) { sceIoWrite(out, "DEV_CAPTURE=end\n", 16); sceIoClose(out); }
    g_devCaptureOffset = -1;
    g_devCapturePath[0] = 0;
}

static void dev_capture_start(int chapter, const char* room) {
    dev_capture_stop();
    char dir[192];
    sceIoMkdir("ux0:data/deltarune/deltarunevita/devlogs", 0777);
    snprintf(dir, sizeof(dir), "ux0:data/deltarune/deltarunevita/devlogs/chapter %d", chapter);
    sceIoMkdir(dir, 0777);
    char safe[64];
    size_t j = 0;
    const char* src = room ? room : "unknown";
    for (size_t i = 0; src[i] && j + 1 < sizeof(safe); i++) {
        char c = src[i];
        safe[j++] = ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                     (c >= '0' && c <= '9') || c == '_' || c == '-') ? c : '_';
    }
    safe[j] = 0;
    SceDateTime now;
    memset(&now, 0, sizeof(now));
    sceRtcGetCurrentClockLocalTime(&now);
    unsigned seq = dev_capture_next_sequence(dir);
    snprintf(g_devCapturePath, sizeof(g_devCapturePath),
             "%s/%u_%s_%04d%02d%02d-%02d%02d%02d.log", dir, seq, safe,
             now.year, now.month, now.day, now.hour, now.minute, now.second);
    SceUID out = sceIoOpen(g_devCapturePath, SCE_O_WRONLY | SCE_O_CREAT | SCE_O_TRUNC, 0666);
    if (out < 0) { g_devCapturePath[0] = 0; return; }
    char header[300];
    int n = snprintf(header, sizeof(header),
        "DELTARUNE_VITA_DEV_CAPTURE=1\nBUILD_VERSION=%s BACKEND=native-gxm\n"
        "CHAPTER=%d LOG_SEQUENCE=%u START_ROOM=%s\n",
        NATIVE_GXM_PROBE_VERSION, chapter, seq, src);
    sceIoWrite(out, header, (SceSize)n);
    sceIoClose(out);
    SceIoStat st;
    g_devCaptureOffset = sceIoGetstat(GXM_NATIVE_LOG, &st) >= 0 ? st.st_size : 0;
}

