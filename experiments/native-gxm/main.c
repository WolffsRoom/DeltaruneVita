static int consume_chapter_request(void) {
    char val='0';
    SceUID fd=sceIoOpen(GX_CHAPTER_MARKER,SCE_O_RDONLY,0);
    if(fd<0)return 0;
    int got=sceIoRead(fd,&val,1);
    sceIoClose(fd);
    sceIoRemove(GX_CHAPTER_MARKER);
    return got==1&&val>='0'&&val<='5'?val-'0':0;
}
static int chapter_from_game_change(const char* workdir) {
    if(!workdir)return -1;
    if(strstr(workdir,"launcher"))return 0;
    const char* p=strstr(workdir,"chapter");
    if(!p)return -1;
    p+=7;
    if(p[0]<'0'||p[0]>'5')return -1;
    if(p[1]>='0'&&p[1]<='9')return -1;
    return p[0]-'0';
}
static int chapter_data_present(int chapter) {
    if(chapter<0||chapter>5)return 0;
    char file[190];
    SceIoStat stat;
    snprintf(file,sizeof(file),GX_CHAPTER_ROOT "%d/data.win",chapter);
    return sceIoGetstat(file,&stat)>=0;
}

