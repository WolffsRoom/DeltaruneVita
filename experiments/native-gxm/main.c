static int restart_into_chapter(int chapter, NVGXMwindow* window) {
    if(!chapter_data_present(chapter)) {
        char line[110];
        snprintf(line,sizeof(line),"NATIVE_GXM=game_change target_missing chapter=%d",chapter);
        log_line(line);
        return -1;
    }
    sceIoMkdir("ux0:data/deltarune_native_gxm_saves",0777);
    SceUID fd=sceIoOpen(GX_CHAPTER_MARKER,
        SCE_O_WRONLY|SCE_O_CREAT|SCE_O_TRUNC,0666);
    if(fd<0){log_line("NATIVE_GXM=game_change marker_open_failed");return -2;}
    char v=(char)('0'+chapter);
    int good=sceIoWrite(fd,&v,1)==1;
    sceIoClose(fd);
    if(!good){sceIoRemove(GX_CHAPTER_MARKER);return -3;}
    char line[120];
    snprintf(line,sizeof(line),"NATIVE_GXM=game_change relaunch_begin chapter=%d",chapter);
    log_line(line);
    sceGxmFinish(window->context);
    sceKernelDelayThread(100000);
    int result=sceAppMgrLoadExec("app0:eboot.bin",NULL,NULL);
    snprintf(line,sizeof(line),"NATIVE_GXM=game_change relaunch_returned result=0x%08X",
             (unsigned)result);
    log_line(line);
    sceIoRemove(GX_CHAPTER_MARKER);
    return result;
}

