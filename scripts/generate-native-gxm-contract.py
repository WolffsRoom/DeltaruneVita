"""Generate typed RendererVtable entries for the native GXM backend.
Implementations live in bs_renderer_impl.inc; any future unimplemented
callback fails explicitly rather than silently claiming success.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
header = (root / "src/butterscotch/src/renderer.h").read_text(encoding="utf-8")
section = header.split("} VertexBuffer;", 1)[1].split("} RendererVtable;", 1)[0]
methods = re.findall(r"^\s*(.*?)\s*\(\*(\w+)\)\((.*)\);", section, flags=re.M)
assert len(methods) >= 60, len(methods)
out = root / "experiments/native-gxm/bs_renderer_contract.c"
lines = [
    "/* GENERATED by scripts/generate-native-gxm-contract.py. */",
    '#include "bs_renderer_contract.h"',
    '#include "matrix_math.h"',
    "#include <psp2/io/fcntl.h>",
    "#include <stdio.h>",
    "#include <stdlib.h>",
    '#define BS_LOG "ux0:data/deltarune/deltarunevita/native-gxm-probe.log"',
    "static void bs_unsupported(const char* what) __attribute__((noreturn));",
    "static void bs_unsupported(const char* what) {",
    "    char msg[156];",
    '    int n=snprintf(msg,sizeof(msg),"NATIVE_GXM=runner_renderer unsupported=%s\\n",what);',
    "    SceUID fd=sceIoOpen(BS_LOG,SCE_O_WRONLY|SCE_O_CREAT|SCE_O_APPEND,0666);",
    "    if (fd >= 0) { sceIoWrite(fd,msg,(unsigned)n); sceIoClose(fd); }",
    "    abort();",
    "}",
    '#include "bs_renderer_impl.inc"',

]
impl = (out.parent / 'bs_renderer_impl.inc').read_text(encoding='utf-8')
implemented = set(re.findall(r'static\s+[^\n;]+?\s+bs_(\w+)\s*\(', impl))
for ret, name, args in methods:
    if name in implemented:
        continue
    lines.append(f"static {ret} bs_{name}({args}) {{ bs_unsupported(\"{name}\"); }}")
lines.append("static RendererVtable bs_vtable = {")
for _ret, name, _args in methods:
    lines.append(f"    .{name} = bs_{name},")
lines.append("};")
lines.extend([
    "Renderer* BSContractRenderer_create(void) {",
    "    Renderer* r=(Renderer*)calloc(1,sizeof(BSGxmRenderer));",
    "    if (!r) return NULL;",
    "    r->vtable=&bs_vtable;",
    "    r->drawColor=0xFFFFFFu; r->drawAlpha=1.0f;",
    "    r->drawFont=-1; r->currentShader=-1;",
    "    return r;",
    "}",
])
out.write_text("\n".join(lines)+"\n", encoding="utf-8")
print("Generated", out.name, "callbacks", len(methods))
